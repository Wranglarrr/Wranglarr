//! nginx: server blocks for conf.d.

use super::{Out, sites, tag, url};
use crate::proxy::{Plan, ProxySettings};

fn ngx_proxy(host: &str) -> [String; 10] {
    [
        "        proxy_http_version 1.1;".into(),
        format!("        proxy_set_header Host {host};"),
        "        proxy_set_header Upgrade $http_upgrade;".into(),
        "        proxy_set_header Connection $wranglarr_upgrade;".into(),
        "        proxy_set_header X-Real-IP $remote_addr;".into(),
        "        proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;".into(),
        "        proxy_set_header X-Forwarded-Proto $scheme;".into(),
        "        proxy_set_header X-Forwarded-Host $host;".into(),
        "        proxy_buffering off;".into(),
        "        proxy_read_timeout 1h;".into(),
    ]
}

pub(super) fn nginx(on: &[&Plan], _s: &ProxySettings, lan: &[String]) -> Out {
    let sites = sites(on);
    let names: Vec<&str> = sites.iter().map(|(f, _)| f.as_str()).collect();
    let mut l: Vec<String> = [
        "# nginx: generated by wranglarr (wranglarr → Reverse proxy). Goes inside http { }, either:",
        "#   Debian/Ubuntu: /etc/nginx/sites-available/arrs, then",
        "#                  sudo ln -s /etc/nginx/sites-available/arrs /etc/nginx/sites-enabled/arrs",
        "#   elsewhere:     /etc/nginx/conf.d/arrs.conf",
        "# then: sudo nginx -t && sudo systemctl reload nginx",
        "#",
        "# Certificates first: nginx won't start while an ssl_certificate file is missing. One per name:",
    ]
    .map(String::from)
    .to_vec();
    l.extend(names.iter().map(|n| format!("#   sudo certbot certonly --nginx -d {n}")));
    l.extend(
        [
            "# (a wildcard *.example.com works too: point the ssl_ lines at its folder instead.)",
            "",
            "map $http_upgrade $wranglarr_upgrade { default upgrade; '' close; }",
            "",
        ]
        .map(String::from),
    );
    let mut allow: Vec<String> = lan.iter().map(|r| format!("        allow {r};")).collect();
    allow.push("        deny all;".into());
    for (fqdn, ps) in &sites {
        l.extend([
            "server {".to_string(),
            "    listen 443 ssl;".into(),
            "    # http2 on;    # nginx 1.25.1 or newer (Debian 12 and Ubuntu 24.04 ship older)".into(),
            format!("    server_name {fqdn};"),
            format!("    ssl_certificate     /etc/letsencrypt/live/{fqdn}/fullchain.pem;"),
            format!("    ssl_certificate_key /etc/letsencrypt/live/{fqdn}/privkey.pem;"),
            "    client_max_body_size 0;".into(),
            String::new(),
        ]);
        for p in ps {
            let loc = if p.path.is_empty() { "/".to_string() } else { format!("{}/", p.path) };
            let target = format!("{}{}", url(&p.up), if p.strip { "/" } else { "" });
            l.push(format!("    # {} ({})", p.name, tag(p)));
            if !p.path.is_empty() {
                l.push(format!("    location = {} {{ return 301 {}/; }}", p.path, p.path));
            }
            l.push(format!("    location {loc} {{"));
            if p.expose == "lan" {
                l.extend(allow.iter().cloned());
            }
            l.push(format!("        proxy_pass {target};"));
            l.extend(ngx_proxy(if p.sab { "$proxy_host" } else { "$host" }));
            l.push("    }".into());
            l.push(String::new());
        }
        l.push("}".into());
        l.push(String::new());
    }
    l.extend([
        "# http -> https; certbot renewals still reach /.well-known/acme-challenge/".to_string(),
        "server {".into(),
        "    listen 80;".into(),
        format!("    server_name {};", names.join(" ")),
        "    location /.well-known/acme-challenge/ { root /var/www/html; }".into(),
        "    location / { return 301 https://$host$request_uri; }".into(),
        "}".into(),
    ]);
    (
        l.join("\n"),
        "arrs.conf",
        "Debian/Ubuntu: save it as /etc/nginx/sites-available/arrs and link it into sites-enabled; elsewhere as \
         /etc/nginx/conf.d/arrs.conf. Get the certificates first, then nginx -t and reload (the top of the file has the commands).",
    )
}
