//! Traefik: a dynamic config file for the file provider, or Docker labels.

use super::{Out, by_target, tag, url};
use crate::proxy::{Plan, ProxySettings};

fn rule(p: &Plan) -> String {
    let r = format!("Host(`{}`)", p.fqdn);
    if p.path.is_empty() { r } else { format!("{r} && PathPrefix(`{}`)", p.path) }
}

fn middlewares(p: &Plan) -> Vec<String> {
    let mut mw = Vec::new();
    if p.expose == "lan" {
        mw.push("wranglarr-lan-only".to_string());
    }
    if p.strip {
        mw.push(format!("{}-strip", p.name));
    }
    mw
}

pub(super) fn file(on: &[&Plan], s: &ProxySettings, lan: &[String]) -> Out {
    let mut l: Vec<String> = [
        "# Traefik dynamic configuration (file provider): generated by wranglarr (wranglarr → Reverse proxy).",
        "# Traefik v3 (on v2, ipAllowList is called ipWhiteList).",
        "http:",
        "  middlewares:",
        "    wranglarr-lan-only:",
        "      ipAllowList:",
        "        sourceRange:",
    ]
    .map(String::from)
    .to_vec();
    l.extend(lan.iter().map(|r| format!("          - \"{r}\"")));
    for p in on {
        if p.strip {
            l.push(format!("    {}-strip:", p.name));
            l.push("      stripPrefix:".into());
            l.push(format!("        prefixes: [\"{}\"]", p.path));
        }
    }
    l.push("  routers:".into());
    for p in on {
        let mw = middlewares(p);
        l.extend([
            format!("    {}:  # {}", p.name, tag(p)),
            format!("      rule: \"{}\"", rule(p)),
            format!("      entryPoints: [{}]", s.entrypoint),
            format!("      service: {}", p.name),
            "      tls:".into(),
            format!("        certResolver: {}", s.resolver),
        ]);
        if !mw.is_empty() {
            l.push(format!("      middlewares: [{}]", mw.join(", ")));
        }
    }
    l.push("  services:".into());
    for p in on {
        l.extend([
            format!("    {}:", p.name),
            "      loadBalancer:".into(),
            "        servers:".into(),
            format!("          - url: \"{}\"", url(&p.up)),
        ]);
        if p.sab {
            l.push("        passHostHeader: false".into());
        }
    }
    (
        l.join("\n") + "\n",
        "wranglarr.yml",
        "Save it in Traefik's dynamic configuration folder (providers.file.directory); Traefik picks it up by itself.",
    )
}

pub(super) fn labels(on: &[&Plan], s: &ProxySettings, lan: &[String]) -> Out {
    let mut l: Vec<String> = [
        "# compose.proxy.yaml: Traefik labels for this stack, generated by wranglarr (wranglarr → Reverse proxy).",
        "# Traefik v3 with the Docker provider (on v2, ipallowlist is ipwhitelist).",
        "services:",
    ]
    .map(String::from)
    .to_vec();
    let mut first = true;
    for (target, ps) in by_target(on) {
        l.extend([
            format!("  {target}:"),
            "    labels:".into(),
            "      - traefik.enable=true".into(),
            format!("      - traefik.docker.network={}", s.network),
        ]);
        if first {
            l.push(format!(
                "      - traefik.http.middlewares.wranglarr-lan-only.ipallowlist.sourcerange={}",
                lan.join(",")
            ));
            first = false;
        }
        for p in ps {
            let r = format!("traefik.http.routers.{}", p.name);
            let mw = middlewares(p);
            l.extend([
                format!("      # {} ({})", p.name, tag(p)),
                format!("      - {r}.rule={}", rule(p)),
                format!("      - {r}.entrypoints={}", s.entrypoint),
                format!("      - {r}.tls.certresolver={}", s.resolver),
                format!("      - {r}.service={}", p.name),
                format!("      - traefik.http.services.{}.loadbalancer.server.port={}", p.name, p.inner),
            ]);
            if p.sab {
                l.push(format!("      - traefik.http.services.{}.loadbalancer.passhostheader=false", p.name));
            }
            if p.strip {
                l.push(format!("      - traefik.http.middlewares.{}-strip.stripprefix.prefixes={}", p.name, p.path));
            }
            if !mw.is_empty() {
                l.push(format!("      - {r}.middlewares={}", mw.join(",")));
            }
        }
        l.push("    networks:".into());
        l.push(format!("      {}: {{}}", s.network));
    }
    l.extend([
        String::new(),
        "networks:".into(),
        format!("  {}:", s.network),
        "    external: true".into(),
        String::new(),
    ]);
    (l.join("\n"), "compose.proxy.yaml", "Save next to compose.yaml, add it to COMPOSE_FILE, docker compose up -d.")
}
