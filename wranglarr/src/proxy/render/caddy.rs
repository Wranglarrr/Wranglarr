//! Caddy: a Caddyfile, or caddy-docker-proxy's Docker labels.

use std::sync::LazyLock;

use regex::Regex;

use super::{Out, by_target, sites, tag};
use crate::proxy::{Plan, ProxySettings};

static NOT_WORD: LazyLock<Regex> = LazyLock::new(|| Regex::new(r"[^A-Za-z0-9_]").expect("static regex"));

fn matcher(p: &Plan) -> String {
    format!("@not_lan_{}", NOT_WORD.replace_all(&p.name, "_"))
}

pub(super) fn caddyfile(on: &[&Plan], s: &ProxySettings, lan: &[String]) -> Out {
    let rng = if s.lan.is_empty() { "private_ranges".to_string() } else { lan.join(" ") };
    let mut l: Vec<String> = vec![
        "# Caddyfile: generated by wranglarr (wranglarr → Reverse proxy). Caddy gets the certificates itself.".into(),
        String::new(),
    ];
    for (fqdn, ps) in sites(on) {
        l.push(format!("{fqdn} {{"));
        for p in &ps {
            if p.expose == "lan" {
                l.push(format!("\t{} not remote_ip {rng}", matcher(p)));
            }
        }
        for p in &ps {
            let mut body = vec![format!("\treverse_proxy {}{}", p.up, if p.sab { " {" } else { "" })];
            if p.sab {
                body.push("\t\theader_up Host {upstream_hostport}".into());
                body.push("\t}".into());
            }
            let lan_line: Vec<String> =
                if p.expose == "lan" { vec![format!("\tabort {}", matcher(p))] } else { vec![] };
            if p.path.is_empty() {
                l.push(format!("\t# {} ({})", p.name, tag(p)));
                l.extend(lan_line);
                l.extend(body);
            } else {
                let d = if p.strip { "handle_path" } else { "handle" };
                let m = if p.strip { format!("{}/*", p.path) } else { format!("{}*", p.path) };
                l.push(String::new());
                l.push(format!("\t# {} ({})", p.name, tag(p)));
                if p.strip {
                    l.push(format!("\tredir {} {}/", p.path, p.path));
                }
                l.push(format!("\t{d} {m} {{"));
                l.extend(lan_line.into_iter().chain(body).map(|x| format!("\t{x}")));
                l.push("\t}".into());
            }
        }
        l.push("}".into());
        l.push(String::new());
    }
    (
        l.join("\n"),
        "Caddyfile",
        "Add these to your Caddyfile and reload Caddy (caddy reload, or restart its container).",
    )
}

pub(super) fn labels(on: &[&Plan], s: &ProxySettings, lan: &[String]) -> Out {
    let rng = if s.lan.is_empty() { "private_ranges".to_string() } else { lan.join(" ") };
    let mut l: Vec<String> = vec![
        "# compose.proxy.yaml: caddy-docker-proxy labels for this stack, generated by wranglarr (wranglarr → Reverse proxy)."
            .into(),
        "services:".into(),
    ];
    for (target, ps) in by_target(on) {
        l.push(format!("  {target}:"));
        l.push("    labels:".into());
        for (i, p) in ps.iter().enumerate() {
            let c = format!("caddy_{i}");
            l.push(format!("      # {} ({})", p.name, tag(p)));
            l.push(format!("      {c}: {}", p.fqdn));
            let mut pre = c.clone();
            if !p.path.is_empty() {
                let d = if p.strip { "handle_path" } else { "handle" };
                pre = format!("{c}.{d}");
                l.push(if p.strip {
                    format!("      {pre}: \"{}/*\"", p.path)
                } else {
                    format!("      {pre}: \"{}*\"", p.path)
                });
            }
            if p.expose == "lan" {
                l.push(format!("      {c}.{}: \"not remote_ip {rng}\"", matcher(p)));
                l.push(format!("      {pre}.abort: \"{}\"", matcher(p)));
            }
            l.push(format!("      {pre}.reverse_proxy: \"{{{{upstreams {}}}}}\"", p.inner));
            if p.sab {
                l.push(format!("      {pre}.reverse_proxy.header_up: \"Host {{upstream_hostport}}\""));
            }
        }
        l.push("    networks:".into());
        l.push(format!("      {}: {{}}", s.network));
    }
    l.extend([
        String::new(),
        "networks:".into(),
        format!("  {}:", s.network),
        "    external: true".into(),
        String::new(),
    ]);
    (l.join("\n"), "compose.proxy.yaml", "Save next to compose.yaml, add it to COMPOSE_FILE, docker compose up -d.")
}
