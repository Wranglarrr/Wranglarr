//! The restore stack's files as text: `compose.yaml`, `.env` and the Postgres
//! init script.

use std::sync::LazyLock;

use regex::Regex;

use super::plan::{Postgres, Stack, StackApp, config_mount, var_name};
use super::{COPY_ENV, NETWORK, env_line, image, q};
use crate::service::AppConfigExt;

static NON_LOWER: LazyLock<Regex> = LazyLock::new(|| Regex::new(r"[^a-z0-9]+").expect("static regex"));

/// `compose.yaml`: Postgres (when there are dumps), then each app, on the restore network.
pub(super) fn compose(st: &Stack) -> String {
    let mut l: Vec<String> = vec![
        format!("# Standalone restore stack: suite {}, version {}.", st.suite.name, st.version),
        format!("# Generated by wranglarr {}. See RESTORE.md. Runs without wranglarr.", crate::VERSION),
        String::new(),
        format!("name: arrs-restore-{}", NON_LOWER.replace_all(&st.suite.name.to_lowercase(), "-")),
        String::new(),
        "services:".into(),
    ];
    if let Some(pg) = &st.postgres {
        l.extend(postgres_service(st.pg_host, pg));
    }
    for a in &st.apps {
        l.extend(app_service(st, a));
    }
    l.extend(["networks:".into(), "  default:".into(), format!("    name: {NETWORK}")]);
    if st.postgres.is_none() {
        l.push(format!(
            "    external: true   # created by the suite that has Postgres; or: docker network create {NETWORK}"
        ));
    }
    l.join("\n") + "\n"
}

fn postgres_service(pg_host: &str, pg: &Postgres) -> Vec<String> {
    vec![
        format!("  {pg_host}:"),
        format!("    image: ${{POSTGRES_IMAGE:-{}}}", pg.image),
        "    restart: unless-stopped".into(),
        "    environment:".into(),
        "      POSTGRES_USER: ${POSTGRES_USER}".into(),
        "      POSTGRES_PASSWORD: ${POSTGRES_PASSWORD}".into(),
        "      TZ: ${TZ}".into(),
        "    volumes:".into(),
        format!(
            "      - ./postgres/data:{}           # created empty; filled from the dumps on first start",
            pg.datadir
        ),
        "      - ./postgres/initdb:/docker-entrypoint-initdb.d:ro".into(),
        "      - ./:/restore:ro".into(),
        "    healthcheck:   # TCP, so it only passes once the restore has finished and the real server is up".into(),
        r#"      test: ["CMD-SHELL", "pg_isready -h 127.0.0.1 -U $${POSTGRES_USER} -d postgres"]"#.into(),
        "      interval: 5s".into(),
        "      timeout: 5s".into(),
        "      retries: 720".into(),
        "    networks: [default]".into(),
        String::new(),
    ]
}

fn app_service(st: &Stack, sa: &StackApp) -> Vec<String> {
    let a = sa.app;
    let info = sa.entry.container.as_ref();
    let mut l = vec![format!("  {}:", a.name)];
    let mut img = format!("    image: {}", image(&a.kind, info, &var_name(&a.name)));
    if let Some(v) = info.map(|i| i.version.as_str()).filter(|v| !v.is_empty()) {
        img.push_str(&format!("   # {v}"));
    }
    l.push(img);
    if sa.behind_vpn {
        l.push("    profiles: [downloads]   # ran behind the VPN before: starts only with --profile downloads".into());
    }
    l.push("    restart: unless-stopped".into());
    if a.def().is_some_and(|d| d.container.run_as_user) {
        // no PUID of its own: runs as that user
        l.push("    init: true".into());
        l.push(r#"    user: "${PUID}:${PGID}""#.into());
    }
    l.push("    environment:".into());
    l.extend(COPY_ENV.iter().map(|k| format!("      {k}: ${{{k}}}")));
    for (k, v) in crate::service::get(&a.kind).map_or(&[][..], |d| d.container.env) {
        l.push(format!("      {k}: {}", q(v)));
    }
    if let (Some(db), Some(kind)) = (&sa.first_db, a.def().and_then(|d| d.database)) {
        l.extend(kind.compose_env(db, st.pg_host));
    }
    l.push("    ports:".into());
    l.extend(sa.ports.iter().map(|p| format!("      - {}", q(p))));
    l.push("    volumes:".into());
    l.push(format!("      - ./{}/config:{}", a.name, config_mount(&a.kind)));
    for b in &sa.binds {
        let v = &b.var;
        l.push(format!("      - ${{{v}:?set {v} in .env}}:{}{}", b.target, if b.ro { ":ro" } else { "" }));
    }
    if st.postgres.is_some() && sa.first_db.is_some() {
        l.extend([
            "    depends_on:".into(),
            format!("      {}:", st.pg_host),
            "        condition: service_healthy".into(),
        ]);
    }
    l.push("    networks: [default]".into());
    l.push(String::new());
    l
}

/// `.env`: the ids and logins, then the data folders (a blank one is marked REQUIRED).
pub(super) fn env_file(st: &Stack) -> String {
    let mut e = vec![
        format!("# restore stack for suite {}, version {}", st.suite.name, st.version),
        "# Host paths below are where the data was mounted when the backup ran; change them if that moved.".into(),
        String::new(),
    ];
    e.extend(st.env.iter().map(|(k, v)| env_line(k, v)));
    for (k, v) in &st.mount_vars {
        e.push(if v.is_empty() {
            format!("{k}=      # REQUIRED: host folder mounted at {}", k.to_lowercase())
        } else {
            env_line(k, v)
        });
    }
    e.join("\n") + "\n"
}

/// `postgres/initdb/10-restore.sh`, which the postgres image runs on an empty data
/// folder: creates and fills every database from its dump.
pub(super) fn initdb(st: &Stack) -> String {
    let mut sh = vec![
        "#!/bin/sh".to_string(),
        format!(
            "# wranglarr {}: recreate the databases of suite {} @ {}.",
            crate::VERSION,
            st.suite.name,
            st.version
        ),
        "# The postgres image runs this once, on an empty data directory.".into(),
        "set -e".into(),
        "restore() {".into(),
        r#"  echo "restore: database $1 from $2""#.into(),
        r#"  psql -v ON_ERROR_STOP=1 -U "$POSTGRES_USER" -d postgres -tAc "SELECT 1 FROM pg_database WHERE datname = '$1'" | grep -q 1 \"#.into(),
        r#"    || createdb -U "$POSTGRES_USER" "$1""#.into(),
        r#"  pg_restore -U "$POSTGRES_USER" -d "$1" --no-owner --no-acl --exit-on-error "/restore/$2""#.into(),
        "}".into(),
    ];
    sh.extend(st.dumps.iter().map(|(db, f)| format!("restore {} {}", q(db), q(f))));
    sh.push(r#"echo "restore: done""#.into());
    sh.join("\n") + "\n"
}
