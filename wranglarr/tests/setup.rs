/// The wizard may run as root in folders other users can write: a link planted
/// where it writes is refused, and nothing lands where the link points.
#[tokio::test]
async fn writes_never_follow_a_planted_link() {
    use std::io::Write;
    use std::os::unix::fs::symlink;
    let ans = json!({"services": ["bazarr"], "postgres_password": "pw", "apps_auth": "manual", "data_root": "/srv/d"});
    let c = client(None);
    let outside = tempfile::tempdir().expect("tmp");
    let shadow = outside.path().join("shadow");
    std::fs::write(&shadow, "root:x:0:0\n").expect("write");
    let nothing_outside = |what: &str| {
        let names: Vec<_> = std::fs::read_dir(outside.path()).expect("ls").flatten().map(|e| e.file_name()).collect();
        assert_eq!(names, [std::ffi::OsString::from("shadow")], "{what}");
        assert_eq!(std::fs::read_to_string(&shadow).expect("read"), "root:x:0:0\n", "{what}");
    };

    // .env is a link: neither backed up through, nor replaced
    let w = start(None, false, &[]).await;
    symlink(&shadow, w.stack.join(".env")).expect("ln");
    let url = format!("{}/api/setup/write", w.url);
    let (s, r) = post(&c, &url, json!({"answers": ans, "overwrite": true})).await;
    assert_eq!(s, 500, "{r}");
    assert!(r["error"].as_str().is_some_and(|e| e.contains(".env is a symbolic link")), "{r}");
    assert!(std::fs::symlink_metadata(w.stack.join(".env")).expect("lstat").file_type().is_symlink());
    nothing_outside(".env");
    // a backup name planted as a link is replaced, not written through
    std::fs::remove_file(w.stack.join(".env")).expect("rm");
    std::fs::write(w.stack.join(".env"), "OLD=1\n").expect("write");
    let now = chrono::Local::now();
    for t in [now, now + chrono::Duration::seconds(1), now + chrono::Duration::seconds(2)] {
        symlink(&shadow, w.stack.join(format!(".env.bak-{}", t.format("%Y%m%d%H%M%S")))).expect("ln");
    }
    let (s, r) = post(&c, &url, json!({"answers": ans, "overwrite": true})).await;
    assert_eq!(s, 500, "{r}");
    assert!(r["error"].as_str().is_some_and(|e| e.contains(".env.bak-")), "{r}");
    assert_eq!(
        std::fs::read_to_string(w.stack.join(".env")).expect("read"),
        "OLD=1\n",
        "untouched when the backup fails"
    );
    nothing_outside(".env.bak");

    // appdata/wranglarr is a link to somewhere else
    let w = start(None, false, &[]).await;
    std::fs::create_dir_all(w.stack.join("appdata")).expect("mkdir");
    symlink(outside.path(), w.stack.join("appdata/wranglarr")).expect("ln");
    let url = format!("{}/api/setup/write", w.url);
    let (s, r) = post(&c, &url, json!({"answers": ans})).await;
    assert_eq!(s, 400, "{r}");
    assert!(r["error"].as_str().is_some_and(|e| e.starts_with("cannot create ./appdata/wranglarr (")), "{r}");
    assert!(!w.stack.join(".env").exists(), "checked before .env is written");
    nothing_outside("appdata/wranglarr");

    // the app's config folder is a link: the restored config.yaml doesn't go there
    let w = start(None, false, &[]).await;
    let ad = w.stack.join("appdata");
    std::fs::create_dir_all(ad.join("old")).expect("mkdir");
    let z = ad.join("old/bazarr.zip");
    let mut zw = zip::ZipWriter::new(std::fs::File::create(&z).expect("zip"));
    zw.start_file("config.yaml", zip::write::SimpleFileOptions::default()).expect("member");
    zw.write_all(b"apikey: secret").expect("write");
    zw.finish().expect("finish");
    std::fs::create_dir_all(ad.join("bazarr")).expect("mkdir");
    symlink(outside.path(), ad.join("bazarr/config")).expect("ln");
    let url = format!("{}/api/setup/write", w.url);
    let (s, r) = post(&c, &url, json!({"answers": ans, "legacy_configs": {"bazarr": z.to_string_lossy()}})).await;
    assert_eq!(s, 500, "{r}");
    assert!(r["error"].as_str().is_some_and(|e| e.contains("bazarr/config is a symbolic link")), "{r}");
    nothing_outside("bazarr/config");
    // a link where the zip should be is refused before anything is written
    std::fs::remove_file(ad.join("bazarr/config")).expect("rm");
    std::fs::remove_file(w.stack.join(".env")).expect("rm");
    symlink(&shadow, ad.join("old/linked.zip")).expect("ln");
    let linked = ad.join("old/linked.zip").to_string_lossy().into_owned();
    let (s, r) = post(&c, &url, json!({"answers": ans, "legacy_configs": {"bazarr": linked}})).await;
    assert_eq!((s, r["error"].as_str().map(str::to_string)), (400, Some(format!("{linked}: not inside appdata"))));
    assert!(!w.stack.join(".env").exists());
}

