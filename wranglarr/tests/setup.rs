fn fixtures() -> Value {
    let text = include_str!("fixtures/setup.json");
    serde_json::from_str(text).expect("fixture json")
}

fn answers(v: &Value) -> Answers {
    serde_json::from_value(v.clone()).expect("answers")
}

/// Leave out the lines that carry today's date, as the fixture does.
fn dated(text: &str) -> String {
    text.split('\n')
        .filter(|l| !l.starts_with("# Generated by") && !l.starts_with("# App logins (wranglarr-setup --auth"))
        .collect::<Vec<_>>()
        .join("\n")
}

fn err<T>(r: wranglarr_core::error::Result<T>) -> Value {
    match r {
        Ok(_) => Value::Null,
        Err(e) => json!(e.to_string()),
    }
}

fn pairs(p: &env::Pairs) -> Value {
    Value::Object(p.iter().map(|(k, v)| (k.to_string(), json!(v))).collect())
}

#[test]
fn files_as_recorded() {
    let f = fixtures();
    let example = std::fs::read_to_string(Path::new(env!("CARGO_MANIFEST_DIR")).join("wranglarr.example.toml"))
        .expect("example toml");
    let target = tempfile::tempdir().expect("tmp");
    let scan = json!({"sqlite": ["radarr", "sonarr"]});
    for c in f["cases"].as_array().expect("cases") {
        let a = answers(&c["answers"]);
        let name = &c["answers"];
        let text = env::render_env(&a, wranglarr::IMAGE).expect("renders");
        assert_eq!(dated(&text), c["env"].as_str().expect("env"), "{name}");
        assert_eq!(dated(&env::mask_secrets(&text)), c["preview"].as_str().expect("preview"), "{name}");
        assert_eq!(env::apply_backup_prefs(&example, &a), c["toml"].as_str().expect("toml"), "{name}");
        if !c["auth_env"].is_null() {
            assert_eq!(pairs(&env::auth_env(&a, &BTreeMap::new()).expect("auth")), c["auth_env"], "{name}");
        }
        let old: BTreeMap<String, String> =
            [("QBITTORRENT_USER", "q"), ("QBITTORRENT_PASSWORD", "old"), ("NZBGET_PASS", "n")]
                .into_iter()
                .map(|(k, v)| (k.to_string(), v.to_string()))
                .collect();
        assert_eq!(pairs(&env::auth_env(&a, &old).expect("auth")), c["auth_env_old"], "{name}");
        assert_eq!(json!(env::auth_steps(&a, true)), c["auth_steps"], "{name}");
        assert_eq!(json!(env::next_steps(&a, &Env::native(), target.path(), &scan, 2)), c["next_steps"], "{name}");
        assert_eq!(err(env::check_auth(&a)), c["check_auth"], "{name}");
        assert_eq!(err(env::check_backup_prefs(&a)), c["check_backup_prefs"], "{name}");
    }
}

#[test]
fn checks_as_recorded() {
    let f = fixtures();
    for b in f["bad"].as_array().expect("bad") {
        let mut v = json!({"services": ["radarr"], "postgres_password": "p", "apps_auth": "manual"});
        for (k, x) in b["answers"].as_object().expect("obj") {
            v[k] = x.clone();
        }
        let a = answers(&v);
        assert_eq!(err(env::check_values(&a)), b["check_values"], "{}", b["answers"]);
        assert_eq!(err(env::check_auth(&a)), b["check_auth"], "{}", b["answers"]);
        assert_eq!(err(env::check_backup_prefs(&a)), b["check_backup_prefs"], "{}", b["answers"]);
    }
    for v in f["vpn"].as_array().expect("vpn") {
        let body: VpnCheck = serde_json::from_value(v["body"].clone()).expect("vpn body");
        assert_eq!(web::check_vpn_json(&body), v["result"], "{}", v["body"]);
    }
    for c in f["set_env_keys"].as_array().expect("set_env_keys") {
        let vals: env::Pairs = c["values"]
            .as_array()
            .expect("values")
            .iter()
            .map(|p| {
                let k: &'static str = env::AUTH_KEYS.iter().find(|k| **k == p[0]).expect("auth key");
                (k, p[1].as_str().expect("str").to_string())
            })
            .collect();
        let out = env::set_env_keys(c["text"].as_str().expect("text"), &vals).expect("set");
        assert_eq!(dated(&out), c["out"].as_str().expect("out"));
    }
}

