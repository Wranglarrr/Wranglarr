struct Running {
    url: String,
    stack: PathBuf,
    _dir: tempfile::TempDir,
}

async fn start(token: Option<&str>, auth_only: bool, files: &[(&str, &str)]) -> Running {
    let dir = tempfile::tempdir().expect("tmp");
    let stack = host::resolve(dir.path()).join("stack");
    std::fs::create_dir_all(&stack).expect("mkdir");
    std::fs::write(stack.join("compose.yaml"), "").expect("compose");
    for (name, text) in files {
        let p = stack.join(name);
        std::fs::create_dir_all(p.parent().expect("parent")).expect("mkdir");
        std::fs::write(p, text).expect("write");
    }
    let w = Wizard { target: stack.clone(), auth_only, token: token.map(str::to_string), env: Env::native() };
    let listener = tokio::net::TcpListener::bind("127.0.0.1:0").await.expect("bind");
    let addr = listener.local_addr().expect("addr");
    tokio::spawn(async move {
        let _ = axum::serve(listener, router(w)).await;
    });
    Running { url: format!("http://{addr}"), stack, _dir: dir }
}

fn client(token: Option<&str>) -> reqwest::Client {
    let mut h = reqwest::header::HeaderMap::new();
    if let Some(t) = token {
        h.insert(reqwest::header::COOKIE, format!("wranglarr_setup={t}").parse().expect("header"));
    }
    reqwest::Client::builder().default_headers(h).redirect(reqwest::redirect::Policy::none()).build().expect("client")
}

/// A POST the way the wizard's page sends it: JSON, with the page's Origin.
async fn post(c: &reqwest::Client, url: &str, body: Value) -> (u16, Value) {
    let origin = url::Url::parse(url).expect("url").origin().ascii_serialization();
    let r = c.post(url).header("origin", origin).json(&body).send().await.expect("post");
    let s = r.status().as_u16();
    (s, r.json().await.unwrap_or(Value::Null))
}

#[tokio::test]
async fn changes_only_from_the_wizards_page() {
    let w = start(Some("t"), false, &[]).await;
    let c = client(Some("t"));
    let url = format!("{}/api/setup/generate", w.url);
    assert_eq!(post(&c, &url, json!({})).await.0, 200);
    // the cookie alone isn't enough: a page on another port of this host gets it too (SameSite)
    let other = url::Url::parse(&w.url).expect("url");
    let other = format!("http://{}:{}", other.host_str().expect("host"), other.port().expect("port") ^ 1);
    for origin in [None, Some("null"), Some(other.as_str()), Some("http://evil.example")] {
        let mut r = c.post(&url).json(&json!({}));
        if let Some(o) = origin {
            r = r.header("origin", o);
        }
        let r = r.send().await.expect("post");
        assert_eq!(r.status(), 403, "Origin {origin:?}");
        let j: Value = r.json().await.expect("json");
        assert_eq!(j["error"], "refused: this request didn't come from the setup wizard's own page");
    }
    // a simple cross-site request (text/plain, no preflight) from the right origin still isn't JSON
    let origin = url::Url::parse(&w.url).expect("url").origin().ascii_serialization();
    let r = c
        .post(&url)
        .header("origin", &origin)
        .header("content-type", "text/plain")
        .body("{}")
        .send()
        .await
        .expect("post");
    assert_eq!(r.status(), 415);
    // reading needs no Origin
    let r = c.get(format!("{}/api/setup/defaults", w.url)).send().await.expect("get");
    assert_eq!(r.status(), 200);
}

#[tokio::test]
async fn token_gate() {
    let w = start(Some("abc123"), false, &[]).await;
    let c = client(None);
    let r = c.get(&w.url).send().await.expect("get");
    assert_eq!(r.status(), 401);
    assert!(r.text().await.expect("text").contains("?t="));
    let r = c.get(format!("{}/api/setup/defaults", w.url)).send().await.expect("get");
    assert_eq!(r.status(), 401);
    assert_eq!(
        r.json::<Value>().await.expect("json")["error"],
        "open the link the setup wizard printed in its terminal"
    );
    assert_eq!(c.get(format!("{}/static/style.css", w.url)).send().await.expect("get").status(), 200);
    let r = c.get(format!("{}/?t=nope", w.url)).send().await.expect("get");
    assert_eq!(r.status(), 401);
    assert!(r.text().await.expect("text").contains("That code doesn't match."));
    assert_eq!(c.get(format!("{}/?t=", w.url)).send().await.expect("get").status(), 401);
    let r = c.get(format!("{}/?t=%20abc123", w.url)).send().await.expect("get");
    assert_eq!(r.status(), 303);
    let sc = r.headers()["set-cookie"].to_str().expect("cookie").to_string();
    assert_eq!(sc, "wranglarr_setup=abc123; HttpOnly; Path=/; SameSite=strict");
    let c = client(Some("abc123"));
    let r = c.get(&w.url).send().await.expect("get");
    assert_eq!(r.status(), 200);
    let page = r.text().await.expect("text");
    let shown = w.stack.to_string_lossy().to_string();
    assert!(page.contains("First-run setup") && page.contains(&shown), "{page}");
    assert_eq!(c.get(format!("{}/docs", w.url)).send().await.expect("get").status(), 404);
    assert_eq!(
        client(Some("abc12")).get(format!("{}/api/setup/defaults", w.url)).send().await.expect("get").status(),
        401
    );
}

