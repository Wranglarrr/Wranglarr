# shellcheck shell=bash
# AuthTunnel files, sourced by scripts/init.sh (APPS_AUTH=tunnel; wiki/App-Logins.md).
#
#   compose.authtunnel.yaml           takes the apps' web ports away and gives them to
#                                     wranglarr-gate (nginx), which asks wranglarr first
#   $APPDATA/gate/gate.conf.template  one nginx server per app, on the app's own port
#
# Both are generated from .env; don't edit them, re-run ./scripts/init.sh --auth.

# app -> port inside its container (= the port the gate listens on), and its .env port variable
declare -A GATE_PORT=([radarr]=7878 [sonarr]=8989 [lidarr]=8686 [prowlarr]=9696 [bazarr]=6767
                      [qbittorrent]=8090 [sabnzbd]=8080 [nzbget]=6789)
declare -A GATE_VAR=([radarr]="RADARR_PORT:-7878" [sonarr]="SONARR_PORT:-8989" [lidarr]="LIDARR_PORT:-8686"
                     [prowlarr]="PROWLARR_PORT:-9696" [bazarr]="BAZARR_PORT:-6767" [qbittorrent]="QBITTORRENT_PORT:-8090"
                     [sabnzbd]="SABNZBD_PORT:-8085" [nzbget]="NZBGET_PORT:-6789")
GATE_ORDER=(radarr sonarr lidarr prowlarr bazarr qbittorrent sabnzbd nzbget)

# the enabled apps the gate fronts
gate_apps() {
  local a out=()
  for a in "${GATE_ORDER[@]}"; do [[ ",$PROFILES," == *",$a,"* ]] && out+=("$a"); done
  echo "${out[*]}"
}

# the apps in the shared VPN tunnel, from COMPOSE_FILE (compose.vpn*.yaml)
vpn_apps() {
  local cf=":$(envget COMPOSE_FILE):"
  [[ $cf == *":compose.vpn.yaml:"* ]] || return 0
  local out="qbittorrent sabnzbd nzbget"
  if [[ $cf == *":compose.vpn-all.yaml:"* ]]; then out+=" prowlarr radarr sonarr lidarr bazarr"
  elif [[ $cf == *":compose.vpn-prowlarr.yaml:"* ]]; then out+=" prowlarr"; fi
  echo "$out"
}

tunnel_compose() {   # $1 = the apps in the shared VPN tunnel (their ports are on `vpn`)
  local inside=" $1 " a
  cat <<'EOF'
# Generated by scripts/init.sh for APPS_AUTH=tunnel. Don't edit: change .env and
# re-run ./scripts/init.sh --auth. See wiki/App-Logins.md.
#
# The apps' web ports move to wranglarr-gate, which lets a request through only
# when the browser is signed in to wranglarr (or it carries the app's API key).
services:
EOF
  [[ -n "$1" ]] && printf '  vpn:\n    ports: !reset []\n'
  for a in $(gate_apps); do
    [[ $inside == *" $a "* ]] && continue          # published on vpn, reset above
    if [[ $a == qbittorrent ]]; then
      printf '  qbittorrent:\n    ports: !override\n      - 6881:6881\n      - 6881:6881/udp\n'
    else
      printf '  %s:\n    ports: !reset []\n' "$a"
    fi
  done
  cat <<'EOF'

  wranglarr-gate:
    image: ${GATE_IMAGE:-docker.io/nginxinc/nginx-unprivileged:1.27-alpine}
    container_name: wranglarr-gate
    restart: unless-stopped
    read_only: true
    tmpfs: [/tmp]
    cap_drop: [ALL]
    security_opt: ["no-new-privileges:true"]
    environment:
      NGINX_ENTRYPOINT_LOCAL_RESOLVERS: "1"
      NGINX_ENVSUBST_OUTPUT_DIR: /tmp/gate
      NGINX_ENVSUBST_FILTER: "^(NGINX_LOCAL_RESOLVERS|WR_)"
      NZBGET_USER: ${NZBGET_USER:-nzbget}
      NZBGET_PASS: ${NZBGET_PASS:-tegbzn6789}
    volumes:
      - ./gate/nginx.conf:/etc/nginx/nginx.conf:ro
      - ./gate/16-wranglarr.envsh:/docker-entrypoint.d/16-wranglarr.envsh:ro
      - ${APPDATA:-./appdata}/gate:/etc/nginx/templates:ro
    ports:
EOF
  for a in $(gate_apps); do printf '      - ${%s}:%s\n' "${GATE_VAR[$a]}" "${GATE_PORT[$a]}"; done
  printf '    networks: [arrs]\n'
}

tunnel_nginx() {
  local a port key host
  cat <<'EOF'
# Generated by scripts/init.sh for APPS_AUTH=tunnel. Don't edit: re-run ./scripts/init.sh --auth.
# Rendered by the nginx image (envsubst) into /tmp/gate/gate.conf at start.
resolver ${NGINX_LOCAL_RESOLVERS} valid=10s ipv6=off;

map $http_upgrade $wr_connection { default upgrade; "" ""; }
# behind your reverse proxy, the address the browser used
map $http_x_forwarded_proto $wr_proto { default $http_x_forwarded_proto; "" $scheme; }
map $http_x_forwarded_host $wr_host { default $http_x_forwarded_host; "" $http_host; }
# API clients (mobile apps, scripts) sign in with the app's API key instead: wranglarr checks it
# against that app's real key, so a made-up key gets nowhere. NZBGet checks its Basic login itself.
map $http_authorization $wr_has_basic { default 0; "~*^basic " 1; }
map $http_authorization $wr_nzbget_auth { default $http_authorization; "" "Basic ${WR_NZBGET_AUTH}"; }
# wranglarr's own cookies (the session, the sign-in's code step) never reach an app: the gate has
# checked them already, and an app that kept one could replay it against wranglarr. Each map drops
# one; a header that still has one after three (a browser can send several) goes without cookies.
map $http_cookie $wr_cookie_1 { default $http_cookie; "~^(?<wr_pre>.*?)(?:^|;\s*)wranglarr_(?:session|mfa)\s*=[^;]*(?<wr_post>.*)$" "$wr_pre$wr_post"; }
map $wr_cookie_1 $wr_cookie_2 { default $wr_cookie_1; "~^(?<wr_pre>.*?)(?:^|;\s*)wranglarr_(?:session|mfa)\s*=[^;]*(?<wr_post>.*)$" "$wr_pre$wr_post"; }
map $wr_cookie_2 $wr_cookie_3 { default $wr_cookie_2; "~^(?<wr_pre>.*?)(?:^|;\s*)wranglarr_(?:session|mfa)\s*=[^;]*(?<wr_post>.*)$" "$wr_pre$wr_post"; }
map $wr_cookie_3 $wr_cookie { default $wr_cookie_3; "~(?:^|;\s*)wranglarr_(?:session|mfa)\s*=" ""; "~^[;\s]+(?<wr_rest>.*)$" $wr_rest; }
EOF
  for a in $(gate_apps); do
    port="${GATE_PORT[$a]}"
    case $a in
      qbittorrent) key='' ;;                                      # logs in with a cookie: no key to check
      nzbget)      key='        if ($wr_skip) { return 204; }' ;;
      *)           key='        proxy_set_header X-Wranglarr-Key $http_x_api_key;
        proxy_set_header X-Wranglarr-Key-Arg $wr_key_arg;' ;;
    esac
    # SABnzbd refuses host names it doesn't know; it knows its own service name
    if [[ $a == sabnzbd ]]; then host='$proxy_host'; else host='$http_host'; fi
    case $a in nzbget) skip='$wr_has_basic' ;; *) skip='0' ;; esac
    cat <<EOF

# ---- $a ----
server {
    listen $port;
    set \$wr_up http://$a:$port;
    set \$wr_gate http://wranglarr:8787/api/auth/gate;
    set \$wr_login "";

    location = /__wranglarr/auth {
        internal;
$key
        proxy_pass \$wr_gate;
        proxy_pass_request_body off;
        proxy_set_header Content-Length "";
        proxy_set_header Host wranglarr;
        proxy_set_header Authorization "";
        proxy_set_header X-Api-Key "";
        proxy_set_header X-Forwarded-Host "";
        proxy_set_header X-Forwarded-Proto "";
        proxy_set_header X-Original-Proto \$wr_proto;
        proxy_set_header X-Original-Host \$wr_host;
        proxy_set_header X-Original-URI \$request_uri;
        proxy_set_header X-Wranglarr-App $a;
    }
    location @wr_login {
        if (\$wr_login = "") { return 401; }
        return 302 \$wr_login;
    }
    location / {
        set \$wr_skip $skip;
        # read here: the auth subrequest has no query string of its own
        set \$wr_key_arg \$arg_apikey;
        auth_request /__wranglarr/auth;
        auth_request_set \$wr_login \$upstream_http_x_wranglarr_login;
        error_page 401 = @wr_login;

        proxy_pass \$wr_up;
        proxy_http_version 1.1;
        proxy_set_header Host $host;
        proxy_set_header Upgrade \$http_upgrade;
        proxy_set_header Connection \$wr_connection;
        proxy_set_header X-Real-IP \$remote_addr;
        proxy_set_header X-Forwarded-For \$proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto \$wr_proto;
        proxy_set_header X-Forwarded-Host \$wr_host;
        proxy_set_header Cookie \$wr_cookie;
EOF
    [[ $a == nzbget ]] && printf '        proxy_set_header Authorization $wr_nzbget_auth;\n'
    cat <<'EOF'
        client_max_body_size 0;
        proxy_buffering off;
        proxy_request_buffering off;
        proxy_read_timeout 1h;
        proxy_send_timeout 1h;
    }
}
EOF
  done
}

# write both files (tunnel) ...
tunnel_write() {
  mkdir -p "$APPDATA/gate"
  tunnel_compose "$(vpn_apps)" > compose.authtunnel.yaml
  tunnel_nginx > "$APPDATA/gate/gate.conf.template"
  chmod 755 "$APPDATA/gate"; chmod 644 "$APPDATA/gate/gate.conf.template" compose.authtunnel.yaml
  echo "init: AuthTunnel: wranglarr-gate fronts $(gate_apps | sed 's/ /, /g')"
}

# ... or remove them (any other mode)
tunnel_remove() {
  rm -f compose.authtunnel.yaml "$APPDATA/gate/gate.conf.template"
}
